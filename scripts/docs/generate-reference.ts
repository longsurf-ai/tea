/** Flags in help text as code, which Mintlify would otherwise turn into dashes. */
// Options, `input@line:col` names and wildcard names such as `request.*`
// read as code, which also keeps Markdown from taking `*` for emphasis.
function flags(text: string): string {
  return text.replace(
    /(?<![`\w-])(--?[A-Za-z][\w-]*(?:=\w+)?|input@\d+:\d+|[a-z]+\.[a-z_]*\*)/g,
    '`$1`',
  );
}

function cliPage(): Page {
  const program = cliProgram(() => {});
  const entries = program.commands.map(command => {
    const usage = `tea ${command.name()} ${command.usage()}`.trim();
    const args = command.registeredArguments.map(argument => ({
      name: argument.name(),
      type: null,
      defaultValue: null,
      description: `${sentence(argument.description)}${argument.required ? '' : ' Optional.'}`,
    }));
    const options = command.options.map(option => {
      const fallback =
        option.negate || option.defaultValue === undefined
          ? ''
          : ` Default: ${option.defaultValueDescription ?? code(String(option.defaultValue))}.`;
      return [
        code(option.flags),
        `${sentence(option.description)}${fallback}${option.mandatory ? ' Required.' : ''}`,
      ];
    });
    const summary = flags(
      punctuate(command.summary() || command.description()),
    );
    const description = flags(punctuate(command.description()));
    return entry({
      name: `tea ${command.name()}`,
      kind: 'command',
      heading: `tea ${command.name()}`,
      summary,
      body: description === summary ? '' : description,
      signatures: [usage],
      params: args,
      table:
        options.length === 0
          ? null
          : {columns: ['Option', 'Description'], rows: options},
      category: 'Commands',
    });
  });
  return {
    route: 'reference/tools/cli',
    title: 'tea command',
    description: punctuate(program.description()),
    intro:
      'The `tea` command compiles, runs and inspects Tea scripts, serves this documentation offline, and runs the language server. Every command accepts `--help`; `tea --version` prints the version. Set the `TEA_LOG` environment variable to `debug`, `info`, `warn` or `error` to change how much the command logs.',
    language: 'bash',
    scope: 'tea',
    paramLabel: 'Argument',
    entries,
    shared: [],
    perEntry: false,
  };
}

// ---- rendering --------------------------------------------------------------

function code(value: string): string {
  const ticks = value.includes('`') ? '``' : '`';
  return `${ticks}${value}${ticks}`;
}

function fence(
  source: string | undefined,
  language = 'tea',
): string | undefined {
  return source === undefined
    ? undefined
    : `\`\`\`${language}\n${source}\n\`\`\``;
}

function joinBlocks(...blocks: readonly (string | undefined)[]): string {
  return blocks
    .filter(block => block !== undefined && block.trim() !== '')
    .join('\n\n');
}

function punctuate(text: string): string {
  return /[.!?]$/.test(text) ? text : `${text}.`;
}

/** Commander help reads `port to bind`; reference tables read sentences. */
function sentence(text: string): string {
  return punctuate(text.charAt(0).toUpperCase() + text.slice(1));
}

/** The slug both renderers give a heading of letters, digits, `_` and spaces. */
function slug(heading: string): string {
  if (!/^[A-Za-z0-9_ ]+$/.test(heading)) {
    throw new Error(
      `heading '${heading}' must hold only letters, digits, _ and spaces`,
    );
  }
  return heading.toLowerCase().replaceAll(' ', '-');
}

function categories(page: Page): Map<string, Entry[]> {
  const grouped = new Map<string, Entry[]>();
  for (const item of page.entries) {
    const list = grouped.get(item.category) ?? [];
    list.push(item);
    grouped.set(item.category, list);
  }
  return grouped;
}

interface Target {
  readonly route: string;
  /** Empty for an entry with its own page. */
  readonly anchor: string;
}

/** Hands out heading slugs for one file, failing on a repeat. */
function headingSlugs(route: string): (heading: string) => string {
  const slugs = new Set<string>();
  return heading => {
    const id = slug(heading);
    // The renderers number repeated headings differently.
    if (slugs.has(id))
      throw new Error(`${route}: two headings read '${heading}'`);
    slugs.add(id);
    return id;
  };
}

/** A member's heading where it shares its page with other entries. */
function memberHeading(page: Page, owner: Entry, member: Entry): string {
  return page.perEntry ? member.heading : `${owner.heading} ${member.heading}`;
}

/**
 * Where each symbol of a page is documented: a heading on a page that lists
 * entries, or, on a per-entry page, the entry's own page, whose methods are
 * headings.
 */
function targets(page: Page): Map<string, Target> {
  const found = new Map<string, Target>();
  if (page.perEntry) {
    const files = new Set<string>();
    for (const item of page.entries) {
      // Entry pages are files: names that differ only in case would collide.
      if (
        !/^\w+$/.test(item.heading) ||
        files.has(item.heading.toLowerCase())
      ) {
        throw new Error(
          `${page.route}: '${item.heading}' cannot name its own page`,
        );
      }
      files.add(item.heading.toLowerCase());
      const route = `${page.route}/${item.heading}`;
      for (const symbol of item.symbols) found.set(symbol, {route, anchor: ''});
      const claim = headingSlugs(route);
      if (item.members.length > 0) claim('Methods');
      for (const member of item.members) {
        found.set(member.name, {route, anchor: claim(member.heading)});
      }
    }
    return found;
  }
  const claim = headingSlugs(page.route);
  if (page.shared.length > 0) claim('Common parameters');
  for (const [category, items] of categories(page)) {
    const categoryId = claim(category.replace(/[^A-Za-z0-9_ ]/g, ''));
    for (const item of items) {
      const id = item.heading === '' ? categoryId : claim(item.heading);
      for (const symbol of item.symbols) {
        found.set(symbol, {route: page.route, anchor: id});
      }
      for (const member of item.members) {
        found.set(member.name, {
          route: page.route,
          anchor: claim(memberHeading(page, item, member)),
        });
      }
    }
  }
  return found;
}

type SymbolIndex = ReadonlyMap<string, Target>;

/** What prose needs to know about the file it is written into. */
interface Place {
  readonly route: string;
  readonly scope: Page['scope'];
}

const LINK = /\{@link\s+([^\s}|]+)(?:\s*\|\s*([^}]+?))?\s*\}/g;

function href(target: Target): string {
  return target.anchor === ''
    ? `/${target.route}`
    : `/${target.route}#${target.anchor}`;
}

/** Resolve `{@link name}` and `{@link name | label}`, then guard MDX syntax. */
function prose(text: string, index: SymbolIndex, place: Place): string {
  const resolved = text.replace(
    LINK,
    (_, target: string, label: string | undefined) => {
      const found = index.get(target);
      if (found === undefined) {
        if (place.scope === 'tea') {
          throw new Error(
            `${place.route}: {@link ${target}} names no documented symbol`,
          );
        }
        return code(label ?? target);
      }
      return `[${code(label ?? target)}](${href(found)})`;
    },
  );
  return escapeMdx(resolved);
}

/** A page description as plain text for front matter: no links, no code marks. */
function plainText(text: string): string {
  return text
    .replace(
      LINK,
      (_, target: string, label: string | undefined) => label ?? target,
    )
    .replaceAll('`', '');
}

/** A description inside another page, where links become code. */
function linkless(text: string): string {
  return escapeMdx(
    text.replace(LINK, (_, target: string, label: string | undefined) =>
      code(label ?? target),
    ),
  );
}

/**
 * Escape `<`, `{` and `}` outside code and formulas, where MDX would read JSX,
 * and `$` outside them, which would start math.
 */
function escapeMdx(markdown: string): string {
  return markdown
    .split(/(```[\s\S]*?```|`[^`\n]*`|^\$\$\n[\s\S]*?\n\$\$$)/gm)
    .map((part, index) =>
      index % 2 === 1
        ? part
        : part.replace(/[<{}$]/g, character => `\\${character}`),
    )
    .join('');
}

function cell(markdown: string): string {
  return markdown.replace(/\s*\n\s*/g, ' ').replace(/\|/g, '\\|');
}

function table(
  columns: readonly string[],
  rows: readonly (readonly string[])[],
): string {
  return [
    `| ${columns.join(' | ')} |`,
    `| ${columns.map(() => '---').join(' | ')} |`,
    ...rows.map(row => `| ${row.map(cell).join(' | ')} |`),
  ].join('\n');
}

function paramTable(
  params: readonly ParamRow[],
  index: SymbolIndex,
  page: Page,
): string {
  const typed = params.some(param => param.type !== null);
  const defaults = params.some(param => param.defaultValue !== null);
  return table(
    [
      page.paramLabel,
      ...(typed ? ['Type'] : []),
      ...(defaults ? ['Default'] : []),
      'Description',
    ],
    params.map(param => [
      code(param.name),
      ...(typed ? [param.type === null ? '' : code(param.type)] : []),
      ...(defaults
        ? [param.defaultValue === null ? '' : code(param.defaultValue)]
        : []),
      prose(param.description, index, page),
    ]),
  );
}

/** Overloads in one block; a long one lists a parameter per line. */
function signatureBlock(item: Entry, page: Page): string | undefined {
  if (item.signatures.length === 0) return undefined;
  const lines =
    page.language === 'tea'
      ? item.signatures.map(signature => wrapSignature(signature))
      : item.signatures;
  return fence(
    lines.join(lines.some(line => line.includes('\n')) ? '\n\n' : '\n'),
    page.language,
  );
}

/** One entry in reading order: summary, syntax, parameters, result, members, sections. */
function entryMarkdown(
  item: Entry,
  index: SymbolIndex,
  page: Page,
  heading?: string,
): string {
  return joinBlocks(
    heading,
    prose(item.summary, index, page),
    signatureBlock(item, page),
    item.params.length === 0 ? undefined : paramTable(item.params, index, page),
    item.returns === null
      ? undefined
      : `**Returns:** ${prose(item.returns, index, page)}`,
    item.table === null
      ? undefined
      : table(
          item.table.columns,
          item.table.rows.map(row =>
            row.map(value => prose(value, index, page)),
          ),
        ),
    prose(item.body, index, page),
  );
}

function frontMatter(title: string, description: string | null): string {
  return joinBlocks(
    `---\ntitle: ${JSON.stringify(title)}${description === null ? '' : `\ndescription: ${JSON.stringify(plainText(description))}`}\n---`,
    GENERATED,
  );
}

/**
 * A page's files by route: one file listing its entries under category
 * headings, or, for a per-entry page, a file listing them by category plus
 * one file for each entry, whose title is its name.
 */
function pageFiles(page: Page, index: SymbolIndex): [string, string][] {
  const grouped = categories(page);
  const intro = prose(page.intro, index, page);
  if (page.perEntry) {
    return [
      [
        page.route,
        joinBlocks(
          frontMatter(page.title, page.description),
          intro,
          ...[...grouped].map(([category, items]) =>
            joinBlocks(
              `## ${category}`,
              table(
                ['Name', 'Description'],
                items.map(item => [
                  `[${code(item.name)}](/${page.route}/${item.heading})`,
                  prose(item.summary, index, page),
                ]),
              ),
            ),
          ),
        ),
      ],
      ...page.entries.map(
        item =>
          [
            `${page.route}/${item.heading}`,
            joinBlocks(
              // The summary opens the body, so no description repeats it.
              frontMatter(item.name, null),
              entryMarkdown(item, index, page),
              item.members.length === 0
                ? undefined
                : joinBlocks(
                    '## Methods',
                    ...item.members.map(member =>
                      entryMarkdown(
                        member,
                        index,
                        page,
                        `### ${member.heading}`,
                      ),
                    ),
                  ),
            ),
          ] as [string, string],
      ),
    ];
  }
  const summaryTable =
    page.entries.length > 3
      ? table(
          ['Name', 'Description'],
          [...grouped.values()]
            .flat()
            .filter(item => item.heading !== '')
            .map(item => [
              `[${code(item.name)}](#${slug(item.heading)})`,
              prose(item.summary, index, page),
            ]),
        )
      : undefined;
  const shared =
    page.shared.length === 0
      ? undefined
      : `## Common parameters\n\n${paramTable(page.shared, index, page)}`;
  const sections = [...grouped].map(([category, items]) =>
    joinBlocks(
      `## ${category}`,
      ...items.map(item =>
        joinBlocks(
          entryMarkdown(
            item,
            index,
            page,
            item.heading === '' ? undefined : `### ${item.heading}`,
          ),
          ...item.members.map(member =>
            entryMarkdown(
              member,
              index,
              page,
              `#### ${memberHeading(page, item, member)}`,
            ),
          ),
        ),
      ),
    ),
  );
  return [
    [
      page.route,
      joinBlocks(
        frontMatter(page.title, page.description),
        intro,
        summaryTable,
        shared,
        ...sections,
      ),
    ],
  ];
}

