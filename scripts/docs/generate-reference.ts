const isLiteral = (value: NativeVar) =>
  value.qualifier === Qualifier.Const && !value.name.includes('.');

function qualifierType(qualifier: string, type: string): string {
  return `${qualifier} ${type}`;
}

/**
 * Facts the catalog states about a parameter, as reader-facing notes. A note
 * appears only when every overload agrees: `input(close)` takes a series even
 * though the other `input` overloads need a constant `defval`.
 */
function parameterNotes(
  overloads: readonly NativeFunc[],
  name: string,
): string {
  const params = overloads.flatMap(overload =>
    overload.params.filter(param => param.name === name),
  );
  const notes: string[] = [];
  if (params.every(param => param.constLiteral)) {
    notes.push('Must be a compile-time constant.');
  }
  if (
    params.every(param => !param.acceptsNa) &&
    params.every(
      param =>
        typeof param.type === 'string' || param.type.kind !== TypeKind.Bool,
    )
  ) {
    notes.push('Cannot be `na`.');
  }
  if (params.every(param => param.mode === 'inout')) {
    notes.push('Must be a variable or field; the call updates it.');
  }
  if (params.every(param => param.capture)) {
    notes.push('Evaluated in the requested context.');
  }
  return notes.join(' ');
}

function nativeParams(
  name: string,
  overloads: readonly NativeFunc[],
): ParamRow[] {
  const doc = NATIVE_FUNCTION_DOCS[name]!;
  const order: string[] = [];
  const types = new Map<string, Set<string>>();
  for (const overload of overloads) {
    for (const param of overload.params) {
      if (param.availability !== 'supported') continue;
      if (!types.has(param.name)) {
        order.push(param.name);
        types.set(param.name, new Set());
      }
      types
        .get(param.name)!
        .add(
          qualifierType(param.qualifierCap, formatNativeTypeRef(param.type)),
        );
    }
  }
  return order.map(param => {
    const prose = doc.params[param];
    if (prose === undefined) {
      throw new Error(
        `native function ${name} does not document parameter ${param}`,
      );
    }
    const notes = parameterNotes(overloads, param);
    return {
      name: param,
      type: [...types.get(param)!].join(', '),
      defaultValue: null,
      description: notes === '' ? prose : `${prose} ${notes}`,
    };
  });
}

function nativeFunctionEntry(
  name: string,
  overloads: readonly NativeFunc[],
): Entry {
  const doc = NATIVE_FUNCTION_DOCS[name];
  if (doc === undefined)
    throw new Error(`native function ${name} has no documentation`);
  return entry({
    name,
    summary: doc.summary,
    signature: overloads.map(formatNativeSignature).join('\n'),
    params: nativeParams(name, overloads),
    returns: doc.returns ?? null,
    body: joinBlocks(doc.details, fence(doc.example)),
    category: doc.category,
  });
}

function valueSignature(value: NativeVar): string {
  const declared = `${value.qualifier} ${formatType(value.type)} ${value.name}`;
  return value.qualifier === Qualifier.Const
    ? `${declared} = ${formatConstant(value)}`
    : declared;
}

function formatConstant(value: NativeVar): string {
  if (typeof value.value === 'string' && value.type.kind === TypeKind.String) {
    return JSON.stringify(value.value);
  }
  return String(value.value);
}

function valueEntries(values: readonly NativeVar[]): Entry[] {
  const entries: Entry[] = [];
  const families = new Set<string>();
  for (const value of values) {
    const key = Object.keys(NATIVE_VALUE_DOCS).find(candidate =>
      candidate.endsWith('*')
        ? value.name.startsWith(candidate.slice(0, -1))
        : candidate === value.name,
    );
    if (key === undefined)
      throw new Error(`native value ${value.name} has no documentation`);
    const doc: NativeValueDoc = NATIVE_VALUE_DOCS[key]!;
    if (!key.endsWith('*')) {
      entries.push(
        entry({
          name: value.name,
          summary: doc.summary,
          signature: valueSignature(value),
          body: joinBlocks(doc.details, fence(doc.example)),
          category: doc.category,
        }),
      );
      continue;
    }
    if (families.has(key)) continue;
    families.add(key);
    const members = values.filter(member =>
      member.name.startsWith(key.slice(0, -1)),
    );
    const notes = members.some(
      member => doc.members?.[member.name] !== undefined,
    );
    entries.push(
      entry({
        name: key,
        // `plot.style_*` reads "plot style"; `color.*` reads "color".
        heading: key.replace(/[*._]+$/, '').replaceAll('.', ' '),
        symbols: members.map(member => member.name),
        summary: doc.summary,
        table: {
          columns: notes
            ? ['Constant', 'Value', 'Description']
            : ['Constant', 'Value'],
          rows: members.map(member => [
            code(member.name),
            code(formatConstant(member)),
            ...(notes ? [doc.members?.[member.name] ?? ''] : []),
          ]),
        },
        body: joinBlocks(
          `Each constant is a ${code(`const ${formatType(members[0]!.type)}`)}.`,
          doc.details,
          fence(doc.example),
        ),
        category: doc.category,
      }),
    );
  }
  return entries;
}

function builtinPages(libraries: readonly TeaLibrary[]): Page[] {
  const values = [...CATALOG.vars.values()].filter(value => !isLiteral(value));
  const placed = new Map<string, string>();
  const place = (name: string, slug: string) => {
    const previous = placed.get(name);
    if (previous !== undefined) {
      throw new Error(`${name} belongs to both ${previous} and ${slug} pages`);
    }
    placed.set(name, slug);
  };
  const pages = BUILTIN_PAGES.map(config => {
    const library =
      config.library === undefined
        ? undefined
        : libraries.find(candidate => candidate.name === config.library)!;
    const functions = [...CATALOG.funcs].filter(([name]) =>
      config.natives(name),
    );
    const pageValues = values.filter(value => config.natives(value.name));
    for (const [name] of functions) place(name, config.slug);
    for (const value of pageValues) place(value.name, config.slug);
    const entries = [
      ...(library === undefined ? [] : libraryEntries(library)),
      ...functions.map(([name, overloads]) =>
        nativeFunctionEntry(name, overloads),
      ),
      ...valueEntries(pageValues),
    ];
    return finishShared(
      {
        route: `reference/builtins/${config.slug}`,
        title: config.title,
        description: config.description,
        intro: joinBlocks(
          config.intro,
          library === undefined ? undefined : libraryIntro(library),
        ),
        language: 'tea',
        scope: 'tea',
        paramLabel: 'Parameter',
        entries,
        shared: [],
      },
      config.shared ?? [],
    );
  });
  const unplaced = [
    ...[...CATALOG.funcs.keys()],
    ...values.map(value => value.name),
  ].filter(name => !placed.has(name));
  if (unplaced.length > 0) {
    throw new Error(`no reference page holds: ${unplaced.join(', ')}`);
  }
  return pages;
}

/** Move parameters documented identically on every entry into one table. */
function finishShared(page: Page, names: readonly string[]): Page {
  if (names.length === 0) return page;
  const shared = new Map<string, ParamRow>();
  const entries = page.entries.map(item => {
    const own = item.params.filter(param => !names.includes(param.name));
    const common = item.params.filter(param => names.includes(param.name));
    for (const param of common) {
      const previous = shared.get(param.name);
      if (
        previous !== undefined &&
        previous.description !== param.description
      ) {
        throw new Error(
          `${page.title}: parameter ${param.name} must read the same on every entry (${item.name})`,
        );
      }
      if (previous !== undefined && previous.type !== param.type) {
        shared.set(param.name, {
          ...previous,
          type: `${previous.type}, ${param.type}`,
        });
      } else if (previous === undefined) {
        shared.set(param.name, param);
      }
    }
    const also =
      common.length === 0
        ? ''
        : `Also accepts the [common parameters](#common-parameters) ${common.map(param => code(param.name)).join(', ')}.`;
    return {...item, params: own, body: joinBlocks(also, item.body)};
  });
  return {
    ...page,
    entries,
    shared: names.flatMap(name =>
      shared.has(name) ? [shared.get(name)!] : [],
    ),
  };
}

// ---- library pages ----------------------------------------------------------

function libraryIntro(library: TeaLibrary): string {
  if (library.doc === null)
    throw new Error(`${library.file}: library() has no doc comment`);
  const access =
    library.access === 'global'
      ? 'Available in every script without an import or namespace.'
      : library.access === 'namespace'
        ? `Available in every script as ${code(`${library.name}.name`)} without an import.`
        : `Add ${code(`import ${library.name}`)} to a script to use these as ${code(`${library.name}.name`)}.`;
  return joinBlocks(library.doc.summary, library.doc.body, access);
}

function memberText(doc: DocComment | null, where: string): string {
  if (doc === null) throw new Error(`${where} has no doc comment`);
  if (doc.body.includes('```')) {
    throw new Error(
      `${where}: member docs render in a table and cannot hold examples`,
    );
  }
  return [
    doc.summary,
    doc.body,
    ...[...doc.params].map(
      ([name, text]) => `${code(name)}: ${punctuate(text)}`,
    ),
    doc.returns === null ? '' : `Returns: ${punctuate(doc.returns)}`,
  ]
    .filter(part => part !== '')
    .join(' ');
}

function librarySignature(library: TeaLibrary, item: LibraryExport): string {
  if (item.kind !== 'function') return item.declaration;
  const params = item.params.map(
    param =>
      `${param.type === null ? '' : `${param.type} `}${param.name}${param.defaultValue === null ? '' : ` = ${param.defaultValue}`}`,
  );
  const name = qualifiedName(library, item.name);
  const single = `${name}(${params.join(', ')})`;
  return single.length <= 80
    ? single
    : `${name}(\n${params.map(param => `    ${param},`).join('\n')}\n)`;
}

// Readers start from what they call, then read the types those calls use.
const READING_ORDER: Readonly<Record<LibraryExport['kind'], number>> = {
  function: 0,
  value: 0,
  type: 1,
  enum: 1,
  interface: 1,
};

function libraryEntries(library: TeaLibrary): Entry[] {
  const exports = [...library.exports].sort(
    (a, b) => READING_ORDER[a.kind] - READING_ORDER[b.kind],
  );
  return exports.map(item => {
    const where = `${library.file}:${item.line} ${item.name}`;
    const doc = item.doc;
    if (doc === null) throw new Error(`${where} has no doc comment`);
    return entry({
      name: qualifiedName(library, item.name),
      heading: item.name,
      summary: doc.summary,
      signature: librarySignature(library, item),
      params: item.params.map(param => {
        const description = doc.params.get(param.name);
        if (description === undefined) {
          throw new Error(`${where} does not document parameter ${param.name}`);
        }
        return {...param, description};
      }),
      returns: doc.returns,
      table:
        item.members.length === 0
          ? null
          : {
              columns: ['Member', 'Description'],
              rows: item.members.map(member => [
                code(member.declaration),
                memberText(
                  member.doc,
                  `${library.file}:${member.line} ${item.name}.${member.name}`,
                ),
              ]),
            },
      body: doc.body,
      category: doc.category ?? 'Declarations',
    });
  });
}

function libraryPages(libraries: readonly TeaLibrary[]): Page[] {
  return libraries
    .filter(library => library.access === 'import')
    .map(library => ({
      route: `reference/libraries/${library.name}`,
      title: library.name,
      description: library.doc?.summary ?? '',
      intro: libraryIntro(library),
      language: 'tea',
      scope: 'tea',
      paramLabel: 'Parameter',
      entries: libraryEntries(library),
      shared: [],
    }));
}

// ---- JavaScript API pages ---------------------------------------------------

const API_CATEGORIES: Readonly<Record<ApiKind, string>> = {
  function: 'Functions',
  class: 'Classes',
  interface: 'Interfaces',
  type: 'Types',
  enum: 'Enums',
  constant: 'Constants',
};

function splitSummary(text: string): {summary: string; rest: string} {
  const [summary = '', ...rest] = text.trim().split(/\n\s*\n/);
  return {summary: summary.replace(/\s*\n\s*/g, ' '), rest: rest.join('\n\n')};
}

function firstSentence(text: string): string {
  return /^.+?[.!?](?=\s|$)/.exec(text)?.[0] ?? text;
}

/**
 * TSDoc examples are Markdown: fenced code stays as written, a sentence with
 * inline code reads as prose, and bare code gets a fence.
 */
function apiExamples(doc: ApiDoc): string {
  return doc.examples
    .map(example =>
      example.includes('```')
        ? example
        : example.includes('`')
          ? `**Example:** ${example}`
          : fence(example, 'ts')!,
    )
    .join('\n\n');
}

function apiEntry(item: ApiExport, heading: string): Entry {
  const {summary, rest} = splitSummary(item.doc.text);
  return entry({
    name: item.name,
    heading,
    summary,
    signature: item.signature,
    params: [...item.doc.params].map(([name, text]) => ({
      name,
      type: null,
      defaultValue: null,
      description: text,
    })),
    returns: item.doc.returns,
    body: joinBlocks(rest, apiExamples(item.doc)),
    symbols: [
      item.name,
      ...item.members.map(member => `${item.name}.${member.name}`),
    ],
    subsections: item.members.map(member => ({
      name: `${item.name}.${member.name}`,
      signature: member.signature,
      text: joinBlocks(
        member.doc.text,
        member.doc.params.size === 0
          ? undefined
          : [...member.doc.params]
              .map(([name, text]) => `- ${code(name)}: ${text}`)
              .join('\n'),
        member.doc.returns === null
          ? undefined
          : `**Returns:** ${member.doc.returns}`,
        apiExamples(member.doc),
      ),
    })),
    category: API_CATEGORIES[item.kind],
  });
}

function javascriptPages(): Page[] {
  return javascriptApi().map(api => {
    const order = Object.keys(API_CATEGORIES);
    const exports = [...api.exports].sort(
      (a, b) =>
        order.indexOf(a.kind) - order.indexOf(b.kind) ||
        a.name.localeCompare(b.name),
    );
    const headed = exports.filter(item => !isTableConstant(item));
    // Headings slug case-insensitively, but `Color` and `color` are two
    // exports: such names carry their kind, "Color class" and "color function".
    const folded = headed.map(item => item.name.toLowerCase());
    const description = splitSummary(api.description ?? '');
    return {
      route: `reference/javascript/${api.specifier === 'tea' ? 'tea' : api.specifier.slice(4).replaceAll('/', '-')}`,
      title: api.specifier,
      description: firstSentence(description.summary),
      intro: joinBlocks(
        `\`\`\`ts\nimport {…} from '${api.specifier}';\n\`\`\``,
        description.summary,
        description.rest,
      ),
      language: 'ts',
      scope: 'javascript',
      paramLabel: 'Parameter',
      shared: [],
      entries: [
        ...headed.map(item =>
          apiEntry(
            item,
            folded.filter(name => name === item.name.toLowerCase()).length > 1
              ? `${item.name} ${item.kind}`
              : item.name,
          ),
        ),
        ...constantTable(exports),
      ],
    };
  });
}

/** A constant whose whole story is one declaration line and a sentence or two. */
function isTableConstant(item: ApiExport): boolean {
  return (
    item.kind === 'constant' &&
    !item.signature.includes('\n') &&
    item.doc.examples.length === 0
  );
}

/** One-line constants, such as the clock units `ms` and `M`, read best as one table. */
function constantTable(exports: readonly ApiExport[]): Entry[] {
  const constants = exports.filter(isTableConstant);
  if (constants.length === 0) return [];
  return [
    entry({
      name: 'Constants',
      heading: '',
      symbols: constants.map(item => item.name),
      summary: '',
      table: {
        columns: ['Constant', 'Declaration', 'Description'],
        rows: constants.map(item => [
          code(item.name),
          code(item.signature.replace(/;$/, '')),
          item.doc.text,
        ]),
      },
      category: API_CATEGORIES.constant,
    }),
  ];
}

