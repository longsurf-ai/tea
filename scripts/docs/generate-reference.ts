function cliPage(): Page {
  const program = cliProgram(() => {});
  const entries = program.commands.map(command => {
    const usage = `tea ${command.name()} ${command.usage()}`.trim();
    const args = command.registeredArguments.map(argument => ({
      name: argument.name(),
      type: null,
      defaultValue: null,
      description: `${sentence(argument.description)}${argument.required ? '' : ' Optional.'}`,
    }));
    const options = command.options.map(option => {
      const fallback =
        option.negate || option.defaultValue === undefined
          ? ''
          : ` Default: ${option.defaultValueDescription ?? code(String(option.defaultValue))}.`;
      return [
        code(option.flags),
        `${sentence(option.description)}${fallback}${option.mandatory ? ' Required.' : ''}`,
      ];
    });
    const summary = punctuate(command.summary() || command.description());
    const description = punctuate(command.description());
    return entry({
      name: `tea ${command.name()}`,
      heading: `tea ${command.name()}`,
      summary,
      body: description === summary ? '' : description,
      signature: usage,
      params: args,
      table:
        options.length === 0
          ? null
          : {columns: ['Option', 'Description'], rows: options},
      category: 'Commands',
    });
  });
  return {
    route: 'reference/tools/cli',
    title: 'tea command',
    description: punctuate(program.description()),
    intro:
      'The `tea` command compiles, runs and inspects Tea scripts, serves this documentation offline, and runs the language server. Every command accepts `--help`; `tea --version` prints the version. Set the `TEA_LOG` environment variable to `debug`, `info`, `warn` or `error` to change how much the command logs.',
    language: 'bash',
    scope: 'tea',
    paramLabel: 'Argument',
    entries,
    shared: [],
  };
}

// ---- rendering --------------------------------------------------------------

function code(value: string): string {
  const ticks = value.includes('`') ? '``' : '`';
  return `${ticks}${value}${ticks}`;
}

function fence(
  source: string | undefined,
  language = 'tea',
): string | undefined {
  return source === undefined
    ? undefined
    : `\`\`\`${language}\n${source}\n\`\`\``;
}

function joinBlocks(...blocks: readonly (string | undefined)[]): string {
  return blocks
    .filter(block => block !== undefined && block.trim() !== '')
    .join('\n\n');
}

function punctuate(text: string): string {
  return /[.!?]$/.test(text) ? text : `${text}.`;
}

/** Commander help reads `port to bind`; reference tables read sentences. */
function sentence(text: string): string {
  return punctuate(text.charAt(0).toUpperCase() + text.slice(1));
}

/** The slug both renderers give a heading of letters, digits, `_` and spaces. */
function slug(heading: string): string {
  if (!/^[A-Za-z0-9_ ]+$/.test(heading)) {
    throw new Error(
      `heading '${heading}' must hold only letters, digits, _ and spaces`,
    );
  }
  return heading.toLowerCase().replaceAll(' ', '-');
}

function categories(page: Page): Map<string, Entry[]> {
  const grouped = new Map<string, Entry[]>();
  for (const item of page.entries) {
    const list = grouped.get(item.category) ?? [];
    list.push(item);
    grouped.set(item.category, list);
  }
  return grouped;
}

interface Target {
  readonly route: string;
  readonly anchor: string;
}

/**
 * Every symbol's anchor on its page. Duplicate slugs are an error because the
 * renderers number repeated headings differently.
 */
function anchors(page: Page): Map<string, string> {
  const symbols = new Map<string, string>();
  const slugs = new Set<string>();
  const claim = (heading: string) => {
    const id = slug(heading);
    if (slugs.has(id))
      throw new Error(`${page.route}: two headings read '${heading}'`);
    slugs.add(id);
    return id;
  };
  if (page.shared.length > 0) claim('Common parameters');
  for (const [category, items] of categories(page)) {
    const categoryId = claim(category.replace(/[^A-Za-z0-9_ ]/g, ''));
    for (const item of items) {
      const id = item.heading === '' ? categoryId : claim(item.heading);
      for (const symbol of item.symbols) symbols.set(symbol, id);
    }
  }
  return symbols;
}

type SymbolIndex = ReadonlyMap<string, Target>;

const LINK = /\{@link\s+([^\s}|]+)(?:\s*\|\s*([^}]+?))?\s*\}/g;

/** Resolve `{@link name}` and `{@link name | label}`, then guard MDX syntax. */
function prose(text: string, index: SymbolIndex, page: Page): string {
  const resolved = text.replace(
    LINK,
    (_, target: string, label: string | undefined) => {
      const found = index.get(target);
      if (found === undefined) {
        if (page.scope === 'tea') {
          throw new Error(
            `${page.route}: {@link ${target}} names no documented symbol`,
          );
        }
        return code(label ?? target);
      }
      const href = `/${found.route}#${found.anchor}`;
      return `[${code(label ?? target)}](${href})`;
    },
  );
  return escapeMdx(resolved);
}

/** A page description as plain text for front matter: no links, no code marks. */
function plainText(text: string): string {
  return text
    .replace(
      LINK,
      (_, target: string, label: string | undefined) => label ?? target,
    )
    .replaceAll('`', '');
}

/** A description inside another page, where links become code. */
function linkless(text: string): string {
  return escapeMdx(
    text.replace(LINK, (_, target: string, label: string | undefined) =>
      code(label ?? target),
    ),
  );
}

/** Escape `<`, `{` and `}` outside code, where MDX would read JSX. */
function escapeMdx(markdown: string): string {
  return markdown
    .split(/(```[\s\S]*?```|`[^`\n]*`)/g)
    .map((part, index) =>
      index % 2 === 1
        ? part
        : part.replace(/[<{}]/g, character => `\\${character}`),
    )
    .join('');
}

function cell(markdown: string): string {
  return markdown.replace(/\s*\n\s*/g, ' ').replace(/\|/g, '\\|');
}

function table(
  columns: readonly string[],
  rows: readonly (readonly string[])[],
): string {
  return [
    `| ${columns.join(' | ')} |`,
    `| ${columns.map(() => '---').join(' | ')} |`,
    ...rows.map(row => `| ${row.map(cell).join(' | ')} |`),
  ].join('\n');
}

function paramTable(
  params: readonly ParamRow[],
  index: SymbolIndex,
  page: Page,
): string {
  const typed = params.some(param => param.type !== null);
  const defaults = params.some(param => param.defaultValue !== null);
  return table(
    [
      page.paramLabel,
      ...(typed ? ['Type'] : []),
      ...(defaults ? ['Default'] : []),
      'Description',
    ],
    params.map(param => [
      code(param.name),
      ...(typed ? [param.type === null ? '' : code(param.type)] : []),
      ...(defaults
        ? [param.defaultValue === null ? '' : code(param.defaultValue)]
        : []),
      prose(param.description, index, page),
    ]),
  );
}

function renderPage(page: Page, index: SymbolIndex): string {
  const grouped = categories(page);
  const summaryTable =
    page.entries.length > 3
      ? table(
          ['Name', 'Description'],
          [...grouped.values()]
            .flat()
            .filter(item => item.heading !== '')
            .map(item => [
              `[${code(item.name)}](#${slug(item.heading)})`,
              prose(item.summary, index, page),
            ]),
        )
      : undefined;
  const shared =
    page.shared.length === 0
      ? undefined
      : `## Common parameters\n\n${paramTable(page.shared, index, page)}`;
  const sections = [...grouped].map(([category, items]) =>
    joinBlocks(
      `## ${category}`,
      ...items.map(item =>
        joinBlocks(
          item.heading === '' ? undefined : `### ${item.heading}`,
          prose(item.summary, index, page),
          fence(item.signature ?? undefined, page.language),
          item.params.length === 0
            ? undefined
            : paramTable(item.params, index, page),
          item.returns === null
            ? undefined
            : `**Returns:** ${prose(item.returns, index, page)}`,
          item.table === null
            ? undefined
            : table(
                item.table.columns,
                item.table.rows.map(row =>
                  row.map(value => prose(value, index, page)),
                ),
              ),
          prose(item.body, index, page),
          ...item.subsections.map(subsection =>
            joinBlocks(
              `**${code(subsection.name)}**`,
              fence(subsection.signature, 'ts'),
              prose(subsection.text, index, page),
            ),
          ),
        ),
      ),
    ),
  );
  return joinBlocks(
    `---\ntitle: ${JSON.stringify(page.title)}\ndescription: ${JSON.stringify(plainText(page.description))}\n---`,
    GENERATED,
    prose(page.intro, index, page),
    summaryTable,
    shared,
    ...sections,
  );
}

// ---- overview ---------------------------------------------------------------

interface NavigationGroup {
  readonly group: string;
  readonly pages: readonly (string | NavigationGroup)[];
}

interface DocsJson {
  readonly navigation: {
    readonly tabs: readonly {
      readonly tab: string;
      readonly groups: readonly NavigationGroup[];
    }[];
  };
}

function frontMatter(text: string, key: string): string {
  const value = new RegExp(`^${key}:\\s*(.+?)\\s*$`, 'm').exec(text)?.[1] ?? '';
  return /^["']/.test(value)
    ? (JSON.parse(value.replace(/^'|'$/g, '"')) as string)
    : value;
}

/**
 * The overview lists the Reference tab of docs.json, which owns navigation.
 * A generated page missing from it, or a listed page that does not exist,
 * fails generation.
 */
async function overviewPage(
  root: string,
  pages: readonly Page[],
): Promise<string> {
  const docs = JSON.parse(
    await readFile(path.join(root, 'docs/docs.json'), 'utf8'),
  ) as DocsJson;
  const tab = docs.navigation.tabs.find(
    candidate => candidate.tab === 'Reference',
  );
  if (tab === undefined) throw new Error('docs.json has no Reference tab');
  const generated = new Map(pages.map(page => [page.route, page]));
  const listed = new Set<string>();
  const sections: string[] = [];
  for (const group of tab.groups) {
    const rows: string[][] = [];
    for (const route of group.pages) {
      if (typeof route !== 'string')
        throw new Error('Reference navigation is one level deep');
      listed.add(route);
      if (route === 'reference/overview') continue;
      const page = generated.get(route);
      let title = page?.title;
      let description = page?.description;
      if (page === undefined) {
        const file = path.join(root, 'docs', `${route}.md`);
        if (!existsSync(file))
          throw new Error(`docs.json lists missing page ${route}`);
        const text = await readFile(file, 'utf8');
        title = frontMatter(text, 'title');
        description = frontMatter(text, 'description');
      }
      rows.push([`[${title}](/${route})`, linkless(description ?? '')]);
    }
    if (rows.length > 0) {
      sections.push(`## ${group.group}`, table(['Page', 'Covers'], rows));
    }
  }
  const unlisted = pages
    .filter(page => !listed.has(page.route))
    .map(page => page.route);
  if (unlisted.length > 0) {
    throw new Error(
      `docs.json does not list generated pages: ${unlisted.join(', ')}`,
    );
  }
  return joinBlocks(
    '---\ntitle: "Reference"\ndescription: "Exact lookup documentation for the Tea language, its built-ins and libraries, the tea command and the JavaScript API."\n---',
    GENERATED,
    'Use the Reference to look up exact syntax and behavior. If you are learning Tea, start with the Documentation tab.',
    '## Reading signatures',
    'Built-in signatures read `name(param: type, optional?: type, ...rest: type) → result`. Parameter tables add the qualifier each argument may have — `const`, `input`, `simple` or `series`, from least to most variable — and any further requirement, such as a compile-time constant. Functions written in Tea, such as `ta` and the libraries, show their declaration as written; a parameter without a type accepts any argument the function body can use. See [Types and qualifiers](/reference/language/types).',
    ...sections,
  );
}

// ---- outputs ----------------------------------------------------------------

function symbolIndex(
  pages: readonly Page[],
  scope: Page['scope'],
): Map<string, Target> {
  const index = new Map<string, Target>();
  for (const page of pages.filter(candidate => candidate.scope === scope)) {
    for (const [symbol, anchor] of anchors(page)) {
      if (index.has(symbol)) {
        // One JavaScript declaration can be exported by several entry points;
        // links go to the first in package.json order.
        if (scope === 'javascript') continue;
        throw new Error(
          `${symbol} is documented on both ${index.get(symbol)!.route} and ${page.route}`,
        );
      }
      index.set(symbol, {route: page.route, anchor});
    }
  }
  return index;
}

/** Every generated reference page, keyed by its file. */
export async function referenceOutputs(
  root = ROOT,
): Promise<ReadonlyMap<string, string>> {
  const libraries = teaLibraries();
  const pages = [
    ...builtinPages(libraries),
    ...libraryPages(libraries),
    cliPage(),
    ...javascriptPages(),
  ];
  const indexes = {
    tea: symbolIndex(pages, 'tea'),
    javascript: symbolIndex(pages, 'javascript'),
  };
  return new Map([
    [
      path.join(root, 'docs/assets/tea.tmLanguage.json'),
      JSON.stringify({...generateGrammar(), name: 'tea', displayName: 'Tea'}),
    ],
    [
      path.join(root, 'docs/reference/overview.md'),
      await overviewPage(root, pages),
    ],
    ...pages.map(
      page =>
        [
          path.join(root, 'docs', `${page.route}.md`),
          renderPage(page, indexes[page.scope]),
        ] as const,
    ),
  ]);
}

/**
 * Turn site routes (`/requests`, `/reference/builtins/ta#tasma`) into links to
 * real sibling files, so the Markdown reads the same on the web and inside an
 * extracted package. A route without a page is an error.
 */
function portableLinks(content: string, file: string, root: string): string {
  return content.replace(
    /\]\(\/([^)#\s]*)(#[^)\s]*)?\)/g,
    (_, route: string, anchor = '') => {
      const target = path.join(root, 'docs', `${route.replace(/\/$/, '')}.md`);
      if (!existsSync(target) && !route.startsWith('reference/')) {
        throw new Error(
          `${path.relative(root, file)} links to missing page /${route}`,
        );
      }
      const relative = path
        .relative(path.dirname(file), target)
        .split(path.sep)
        .join('/');
      return `](${relative.startsWith('.') ? relative : `./${relative}`}${anchor})`;
    },
  );
}

async function generatedFiles(directory: string): Promise<string[]> {
  const found: string[] = [];
  for (const item of await readdir(directory, {withFileTypes: true})) {
    const file = path.join(directory, item.name);
    if (item.isDirectory()) found.push(...(await generatedFiles(file)));
    else if (
      item.name.endsWith('.md') &&
      (await readFile(file, 'utf8')).includes(GENERATED)
    ) {
      found.push(file);
    }
  }
  return found;
}

interface GenerateOptions {
  readonly root?: string;
  readonly check?: boolean;
  readonly report?: (message: string) => void;
}

/** Write the reference, or with `check` report every file that would change. */
export async function generateReference(
  options: GenerateOptions = {},
): Promise<boolean> {
  const root = options.root ?? ROOT;
  const check = options.check ?? false;
  const report = options.report ?? (message => console.error(message));
  let stale = false;
  const outputs = await referenceOutputs(root);
  for (const [file, content] of outputs) {
    const formatted = await format(
      path.extname(file) === '.json'
        ? content
        : portableLinks(content, file, root),
      {parser: path.extname(file) === '.json' ? 'json' : 'mdx'},
    );
    const current = existsSync(file) ? await readFile(file, 'utf8') : undefined;
    if (current === formatted) continue;
    if (check) {
      stale = true;
      report(`Generated reference is stale: ${path.relative(root, file)}`);
      continue;
    }
    await mkdir(path.dirname(file), {recursive: true});
    await writeFile(file, formatted, 'utf8');
  }
  for (const file of await generatedFiles(path.join(root, 'docs/reference'))) {
    if (outputs.has(file)) continue;
    if (check) {
      stale = true;
      report(
        `Generated reference page has no source: ${path.relative(root, file)}`,
      );
      continue;
    }
    await rm(file);
    // Drop directories the removed page leaves empty, up to docs/reference.
    for (
      let directory = path.dirname(file);
      directory !== path.join(root, 'docs/reference') &&
      (await readdir(directory)).length === 0;
      directory = path.dirname(directory)
    ) {
      await rm(directory, {recursive: true});
    }
  }
  if (!stale && check) console.log('Generated Tea reference is current.');
  return !stale;
}

if (
  process.argv[1] !== undefined &&
  path.resolve(process.argv[1]) === SCRIPT_FILE
) {
  const current = await generateReference({
    check: process.argv.includes('--check'),
  });
  if (!current) process.exitCode = 1;
}
