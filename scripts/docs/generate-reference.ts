const isLiteral = (value: NativeVar) =>
  value.qualifier === Qualifier.Const && !value.name.includes('.');

function qualifierType(qualifier: string, type: string): string {
  return `${qualifier} ${type}`;
}

/**
 * Facts the catalog states about a parameter, as reader-facing notes. A note
 * appears only when every overload agrees: `input(close)` takes a series even
 * though the other `input` overloads need a constant `defval`.
 */
function parameterNotes(
  overloads: readonly NativeFunc[],
  name: string,
): string {
  const params = overloads.flatMap(overload =>
    overload.params.filter(param => param.name === name),
  );
  const notes: string[] = [];
  if (params.every(param => param.constLiteral)) {
    notes.push('Must be a compile-time constant.');
  }
  if (
    params.every(param => !param.acceptsNa) &&
    params.every(
      param =>
        typeof param.type === 'string' || param.type.kind !== TypeKind.Bool,
    )
  ) {
    notes.push('Cannot be `na`.');
  }
  if (params.every(param => param.mode === 'inout')) {
    notes.push('Must be a variable or field; the call updates it.');
  }
  if (params.every(param => param.capture)) {
    notes.push('Evaluated in the requested context.');
  }
  return notes.join(' ');
}

function nativeParams(
  name: string,
  overloads: readonly NativeFunc[],
): ParamRow[] {
  const doc = NATIVE_FUNCTION_DOCS[name]!;
  const order: string[] = [];
  const types = new Map<string, Set<string>>();
  for (const overload of overloads) {
    for (const param of overload.params) {
      if (param.availability !== 'supported') continue;
      if (!types.has(param.name)) {
        order.push(param.name);
        types.set(param.name, new Set());
      }
      types
        .get(param.name)!
        .add(
          qualifierType(param.qualifierCap, formatNativeTypeRef(param.type)),
        );
    }
  }
  return order.map(param => {
    const prose = doc.params[param];
    if (prose === undefined) {
      throw new Error(
        `native function ${name} does not document parameter ${param}`,
      );
    }
    const notes = parameterNotes(overloads, param);
    return {
      name: param,
      type: [...types.get(param)!].join(', '),
      defaultValue: null,
      description: notes === '' ? prose : `${prose} ${notes}`,
    };
  });
}

function nativeFunctionEntry(
  name: string,
  overloads: readonly NativeFunc[],
  outputs: Outputs,
): Entry {
  const doc = nativeFunctionDocs(name);
  if (doc === null)
    throw new Error(`native function ${name} has no documentation`);
  return entry({
    name,
    kind: 'function',
    summary: doc.summary,
    signatures: overloads.map(formatNativeSignature),
    params: nativeParams(name, overloads),
    returns: doc.returns,
    body: docSections(doc, outputs(doc)),
    pine: doc.pine,
    category: doc.category!,
  });
}

function valueSignature(value: NativeVar): string {
  const declared = `${value.qualifier} ${formatType(value.type)} ${value.name}`;
  return value.qualifier === Qualifier.Const
    ? `${declared} = ${formatConstant(value)}`
    : declared;
}

function formatConstant(value: NativeVar): string {
  if (typeof value.value === 'string' && value.type.kind === TypeKind.String) {
    return JSON.stringify(value.value);
  }
  return String(value.value);
}

function valueEntries(values: readonly NativeVar[], outputs: Outputs): Entry[] {
  const entries: Entry[] = [];
  const families = new Set<string>();
  for (const value of values) {
    const key = Object.keys(NATIVE_VALUE_DOCS).find(candidate =>
      candidate.endsWith('*')
        ? value.name.startsWith(candidate.slice(0, -1))
        : candidate === value.name,
    );
    if (key === undefined)
      throw new Error(`native value ${value.name} has no documentation`);
    const members = NATIVE_VALUE_DOCS[key]!.members;
    const doc = nativeValueDocs(key)!;
    if (!key.endsWith('*')) {
      entries.push(
        entry({
          name: value.name,
          kind: value.qualifier === Qualifier.Const ? 'constant' : 'variable',
          summary: doc.summary,
          signatures: [valueSignature(value)],
          body: docSections(doc, outputs(doc)),
          pine: doc.pine,
          category: doc.category!,
        }),
      );
      continue;
    }
    if (families.has(key)) continue;
    families.add(key);
    const family = values.filter(member =>
      member.name.startsWith(key.slice(0, -1)),
    );
    const notes = family.some(member => members?.[member.name] !== undefined);
    entries.push(
      entry({
        name: key,
        kind: 'constant',
        // `plot.style_*` reads "plot style"; `color.*` reads "color".
        heading: key.replace(/[*._]+$/, '').replaceAll('.', ' '),
        symbols: family.map(member => member.name),
        summary: doc.summary,
        table: {
          columns: notes
            ? ['Constant', 'Value', 'Description']
            : ['Constant', 'Value'],
          rows: family.map(member => [
            code(member.name),
            code(formatConstant(member)),
            ...(notes ? [members?.[member.name] ?? ''] : []),
          ]),
        },
        body: joinBlocks(
          `Each constant is a ${code(`const ${formatType(family[0]!.type)}`)}.`,
          docSections(doc, outputs(doc)),
        ),
        pine: doc.pine,
        category: doc.category!,
      }),
    );
  }
  return entries;
}

function builtinPages(
  libraries: readonly TeaLibrary[],
  outputs: Outputs,
): Page[] {
  const values = [...CATALOG.vars.values()].filter(value => !isLiteral(value));
  const placed = new Map<string, string>();
  const place = (name: string, slug: string) => {
    const previous = placed.get(name);
    if (previous !== undefined) {
      throw new Error(`${name} belongs to both ${previous} and ${slug} pages`);
    }
    placed.set(name, slug);
  };
  const pages = BUILTIN_PAGES.map(config => {
    const library =
      config.library === undefined
        ? undefined
        : libraries.find(candidate => candidate.name === config.library)!;
    const functions = [...CATALOG.funcs].filter(([name]) =>
      config.natives(name),
    );
    const pageValues = values.filter(value => config.natives(value.name));
    for (const [name] of functions) place(name, config.slug);
    for (const value of pageValues) place(value.name, config.slug);
    const exported =
      library === undefined
        ? []
        : libraryEntries(library, outputs).filter(
            item => config.categories?.(item.category) ?? true,
          );
    for (const item of exported) place(item.name, config.slug);
    const entries = [
      ...exported,
      ...functions.map(([name, overloads]) =>
        nativeFunctionEntry(name, overloads, outputs),
      ),
      ...valueEntries(pageValues, outputs),
    ];
    return finishShared(
      {
        route: `reference/builtins/${config.slug}`,
        title: config.title,
        description: config.description,
        intro: joinBlocks(
          config.intro,
          library === undefined ? undefined : libraryIntro(library, outputs),
        ),
        language: 'tea',
        scope: 'tea',
        paramLabel: 'Parameter',
        entries,
        shared: [],
        perEntry: config.perEntry ?? false,
      },
      config.shared ?? [],
    );
  });
  const unplaced = [
    ...[...CATALOG.funcs.keys()],
    ...values.map(value => value.name),
    ...libraries
      .filter(library => library.access !== 'import')
      .flatMap(library =>
        library.exports.map(item => qualifiedName(library, item.name)),
      ),
  ].filter(name => !placed.has(name));
  if (unplaced.length > 0) {
    throw new Error(`no reference page holds: ${unplaced.join(', ')}`);
  }
  return pages;
}

/** Move parameters documented identically on every entry into one table. */
function finishShared(page: Page, names: readonly string[]): Page {
  if (names.length === 0) return page;
  const shared = new Map<string, ParamRow>();
  const entries = page.entries.map(item => {
    const own = item.params.filter(param => !names.includes(param.name));
    const common = item.params.filter(param => names.includes(param.name));
    for (const param of common) {
      const previous = shared.get(param.name);
      if (
        previous !== undefined &&
        previous.description !== param.description
      ) {
        throw new Error(
          `${page.title}: parameter ${param.name} must read the same on every entry (${item.name})`,
        );
      }
      if (previous !== undefined && previous.type !== param.type) {
        shared.set(param.name, {
          ...previous,
          type: `${previous.type}, ${param.type}`,
        });
      } else if (previous === undefined) {
        shared.set(param.name, param);
      }
    }
    const also =
      common.length === 0
        ? ''
        : `Also accepts the [common parameters](#common-parameters) ${common.map(param => code(param.name)).join(', ')}.`;
    return {...item, params: own, body: joinBlocks(also, item.body)};
  });
  return {
    ...page,
    entries,
    shared: names.flatMap(name =>
      shared.has(name) ? [shared.get(name)!] : [],
    ),
  };
}

// ---- library pages ----------------------------------------------------------

function libraryIntro(library: TeaLibrary, outputs: Outputs): string {
  if (library.doc === null)
    throw new Error(`${library.file}: library() has no doc comment`);
  const access =
    library.access === 'global'
      ? 'Available in every script without an import or namespace.'
      : library.access === 'namespace'
        ? `Available in every script as ${code(`${library.name}.name`)} without an import.`
        : `Add ${code(`import ${library.name}`)} to a script to use these as ${code(`${library.name}.name`)}.`;
  return joinBlocks(
    library.doc.summary,
    docSections(library.doc, outputs(library.doc)),
    access,
  );
}

function memberText(doc: DocComment | null, where: string): string {
  if (doc === null) throw new Error(`${where} has no doc comment`);
  if (docSections({...doc, body: ''}) !== '' || doc.body.includes('```')) {
    throw new Error(
      `${where}: field and enum member docs render in a table and cannot hold examples or other sections`,
    );
  }
  return [doc.summary, doc.body].filter(part => part !== '').join(' ');
}

/**
 * Library text as a script writes it: the library's own types, enums and
 * interfaces, which its source names bare, gain its namespace, so
 * `Commission.new(CommissionKind.rate, 0.0)` reads
 * `broker.Commission.new(broker.CommissionKind.rate, 0.0)`. Strings stay.
 */
function qualify(library: TeaLibrary, text: string): string {
  if (library.access === 'global') return text;
  const types = new Set(
    library.exports
      .filter(item => item.kind !== 'function' && item.kind !== 'value')
      .map(item => item.name),
  );
  return text
    .split(/("(?:[^"\\]|\\.)*")/)
    .map((part, index) =>
      index % 2 === 1
        ? part
        : part.replace(/(?<![.\w])[A-Za-z_]\w*/g, word =>
            types.has(word) ? `${library.name}.${word}` : word,
          ),
    )
    .join('');
}

function libraryParams(
  library: TeaLibrary,
  params: readonly LibraryParam[],
  doc: DocComment,
  where: string,
): ParamRow[] {
  return params.map(param => {
    const description = doc.params.get(param.name);
    if (description === undefined) {
      throw new Error(`${where} does not document parameter ${param.name}`);
    }
    return {
      name: param.name,
      type: param.type === null ? null : qualify(library, param.type),
      defaultValue:
        param.defaultValue === null
          ? null
          : qualify(library, param.defaultValue),
      description,
    };
  });
}

function librarySignature(library: TeaLibrary, item: LibraryExport): string {
  if (item.kind === 'value') {
    // A value's type is the checker's: what an editor shows for it.
    const source = `x = ${qualifiedName(library, item.name)}`;
    const shown = hover(analyze({filename: 'value.tea', source}), {
      line: 0,
      character: source.length - 1,
    });
    const line = /^```tea\n(.+) \w+\n/.exec(
      (shown?.contents as {value: string} | undefined)?.value ?? '',
    );
    if (line === null)
      throw new Error(`${library.file}: no type for ${item.name}`);
    return `${line[1]} ${qualifiedName(library, item.name)}`;
  }
  if (item.kind !== 'function') return item.declaration;
  const params = item.params.map(param =>
    qualify(
      library,
      `${param.type === null ? '' : `${param.type} `}${param.name}${param.defaultValue === null ? '' : ` = ${param.defaultValue}`}`,
    ),
  );
  return `${qualifiedName(library, item.name)}(${params.join(', ')})`;
}

// Readers start from what they call, then read the types those calls use.
const READING_ORDER: Readonly<Record<LibraryExport['kind'], number>> = {
  function: 0,
  value: 0,
  type: 1,
  enum: 1,
  interface: 1,
};

function libraryEntries(library: TeaLibrary, outputs: Outputs): Entry[] {
  const exports = [...library.exports].sort(
    (a, b) => READING_ORDER[a.kind] - READING_ORDER[b.kind],
  );
  return exports.map(item => {
    const where = `${library.file}:${item.line} ${item.name}`;
    const doc = item.doc;
    if (doc === null) throw new Error(`${where} has no doc comment`);
    const name = qualifiedName(library, item.name);
    const category = doc.category ?? 'Declarations';
    const listed = item.members.filter(member => member.kind !== 'method');
    return entry({
      name,
      kind: item.kind === 'value' ? 'variable' : item.kind,
      heading: item.name,
      summary: doc.summary,
      signatures: [librarySignature(library, item)],
      params: libraryParams(library, item.params, doc, where),
      returns: doc.returns,
      table:
        listed.length === 0
          ? null
          : {
              columns: [
                item.kind === 'enum' ? 'Member' : 'Field',
                'Description',
              ],
              rows: listed.map(member => [
                code(qualify(library, member.declaration)),
                memberText(
                  member.doc,
                  `${library.file}:${member.line} ${item.name}.${member.name}`,
                ),
              ]),
            },
      body: docSections(doc, outputs(doc)),
      pine: doc.pine,
      members: item.members
        .filter(member => member.kind === 'method')
        .map(member => {
          const at = `${library.file}:${member.line} ${item.name}.${member.name}`;
          if (member.doc === null) throw new Error(`${at} has no doc comment`);
          return entry({
            name: `${name}.${member.name}`,
            kind: 'function',
            heading: member.name,
            summary: member.doc.summary,
            signatures: [qualify(library, member.declaration)],
            params: libraryParams(library, member.params, member.doc, at),
            returns: member.doc.returns,
            body: docSections(member.doc, outputs(member.doc)),
            pine: member.doc.pine,
            category,
          });
        }),
      category,
    });
  });
}

