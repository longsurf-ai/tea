/**
 * Every Tea name in one table, sorted ignoring case: entries, methods, and
 * the language's keywords and operators, each linked to where it is
 * documented.
 */
async function indexArticle(
  root: string,
  pages: readonly Page[],
  index: SymbolIndex,
): Promise<Article> {
  const rows: [string, string, string, string][] = [];
  for (const page of pages.filter(candidate => candidate.scope === 'tea')) {
    for (const item of page.entries) {
      if (item.heading === '') continue;
      rows.push([
        item.name,
        entryLink(item, index),
        ENTRY_KINDS[item.kind],
        linkless(item.summary),
      ]);
      for (const member of item.members) {
        rows.push([
          member.name,
          entryLink(member, index),
          'method',
          linkless(member.summary),
        ]);
      }
    }
  }
  const language = await Promise.all(
    LANGUAGE_PAGES.map(async name => ({
      name,
      headings: (
        await readFile(
          path.join(root, `docs/reference/language/${name}.md`),
          'utf8',
        )
      )
        .split('\n')
        .filter(line => line.startsWith('#'))
        .flatMap(line =>
          [...line.matchAll(/`([^`]+)`/g)].map(match => match[1]!),
        ),
    })),
  );
  for (const token of LANGUAGE_TOKENS) {
    const page = language.find(candidate => candidate.headings.includes(token));
    if (page === undefined) {
      throw new Error(`no Language page heading names ${token}`);
    }
    rows.push([
      token,
      `[${code(token)}](/reference/language/${page.name})`,
      (KEYWORDS as readonly string[]).includes(token) ? 'keyword' : 'syntax',
      '',
    ]);
  }
  const sorted = (tokens: boolean) =>
    rows
      .filter(
        ([, , kind]) => (kind === 'keyword' || kind === 'syntax') === tokens,
      )
      .sort(
        ([a], [b]) =>
          a.localeCompare(b, 'en', {sensitivity: 'base'}) || a.localeCompare(b),
      );
  return {
    route: 'reference/a-z',
    title: 'A–Z index',
    description: 'Every name and keyword a Tea script can use, in one list.',
    markdown: joinBlocks(
      '## Names',
      table(
        ['Name', 'Kind', 'Summary'],
        sorted(false).map(([, link, kind, summary]) => [link, kind, summary]),
      ),
      '## Keywords and operators',
      table(
        ['Token', 'Kind'],
        sorted(true).map(([, link, kind]) => [link, kind]),
      ),
    ),
  };
}

/** Pine Script differences from library notes, entries and staged parameters. */
function pineArticle(
  libraries: readonly TeaLibrary[],
  pages: readonly Page[],
  index: SymbolIndex,
): Article {
  const missing = libraries.flatMap(library =>
    library.doc?.pine == null
      ? []
      : [joinBlocks(`### ${library.name}`, library.doc.pine)],
  );
  const staged = [...CATALOG.funcs].flatMap(([name, overloads]) => {
    const params = [
      ...new Set(
        overloads.flatMap(overload =>
          overload.params
            .filter(param => param.availability === 'staged')
            .map(param => code(param.name)),
        ),
      ),
    ];
    return params.length === 0
      ? []
      : [[`[${code(name)}](${href(index.get(name)!)})`, params.join(', ')]];
  });
  const differences = pages
    .filter(page => page.scope === 'tea')
    .flatMap(page => page.entries.flatMap(item => [item, ...item.members]))
    .flatMap(item =>
      item.pine === null ? [] : [[entryLink(item, index), item.pine]],
    );
  return {
    route: 'reference/pine-compatibility',
    title: 'Pine Script compatibility',
    description:
      'What Tea does not have yet, and where it behaves differently from Pine Script v6.',
    markdown: joinBlocks(
      'Tea follows Pine Script v6: a name both have behaves the same way unless this page lists it. A Pine name missing from the [A–Z index](/reference/a-z) is not in Tea yet. Some differences are in the language itself:',
      [
        '- A collection is a value: assigning it or passing it to a function copies it, where Pine Script shares a reference (see [memory model](/memory-model)).',
        '- A request has no `lookahead` or `gaps` argument and never waits for a requested bar to close: each bar sees the newest requested bar that opened at or before it, so with completed daily data an intraday bar sees that day’s close (see [Request synchronization](/requests)).',
        '- A function called under a condition keeps its history only on the bars where it runs (see [values and control flow](/language-guide/values-and-control-flow)).',
        '- A function name is declared once: Tea has no overloading by parameter types or count, so a Pine library that overloads a name needs one untyped function or separate names (see [declarations](/reference/language/declarations#functions)).',
      ].join('\n'),
      missing.length === 0 ? undefined : joinBlocks('## Libraries', ...missing),
      staged.length === 0
        ? undefined
        : joinBlocks(
            '## Parameters not supported yet',
            'Tea accepts these Pine Script parameters by position but rejects any argument for them.',
            table(['Function', 'Parameters'], staged),
          ),
      differences.length === 0
        ? undefined
        : joinBlocks(
            '## Functions and values',
            table(['Name', 'In Tea'], differences),
          ),
    ),
  };
}

function articleFile(article: Article, index: SymbolIndex): string {
  return joinBlocks(
    frontMatter(article.title, article.description),
    prose(article.markdown, index, {route: article.route, scope: 'tea'}),
  );
}

// ---- navigation -------------------------------------------------------------

interface NavigationGroup {
  readonly group: string;
  /** The page a group opens, such as `ta`'s namespace page. */
  readonly root?: string;
  readonly pages: readonly (string | NavigationGroup)[];
}

interface DocsJson {
  readonly navigation: {
    readonly tabs: readonly {
      readonly tab: string;
      readonly groups: readonly NavigationGroup[];
    }[];
  };
}

async function referenceTab(root: string): Promise<readonly NavigationGroup[]> {
  const docs = JSON.parse(
    await readFile(path.join(root, 'docs/docs.json'), 'utf8'),
  ) as DocsJson;
  const tab = docs.navigation.tabs.find(
    candidate => candidate.tab === 'Reference',
  );
  if (tab === undefined) throw new Error('docs.json has no Reference tab');
  return tab.groups;
}

/**
 * The page that opens a group: its root, or a per-entry page listed first in
 * a section heading such as Technical analysis. A section has no root, since
 * Mintlify draws a top-level group with a root as an expandable item.
 */
function openingPage(
  group: NavigationGroup,
  generated: ReadonlyMap<string, Page>,
): string | undefined {
  const [first] = group.pages;
  return (
    group.root ??
    (typeof first === 'string' && generated.get(first)?.perEntry
      ? first
      : undefined)
  );
}

function frontMatterValue(text: string, key: string): string {
  const value = new RegExp(`^${key}:\\s*(.+?)\\s*$`, 'm').exec(text)?.[1] ?? '';
  return /^["']/.test(value)
    ? (JSON.parse(value.replace(/^'|'$/g, '"')) as string)
    : value;
}

/**
 * docs.json owns navigation; generation checks it. Every generated page is
 * listed exactly once, and a per-entry page opens a group (see
 * {@link openingPage}) whose other pages are one group per category, listing
 * its entry pages in order. A mismatch prints the `pages` the group needs.
 */
async function checkNavigation(
  root: string,
  pages: readonly Page[],
  articles: readonly Article[],
): Promise<void> {
  const generated = new Map(pages.map(page => [page.route, page]));
  const listed = new Set<string>();
  const list = (route: string) => {
    if (listed.has(route)) throw new Error(`docs.json lists ${route} twice`);
    listed.add(route);
  };
  const walk = (group: NavigationGroup) => {
    const opening = openingPage(group, generated);
    const page = opening === undefined ? undefined : generated.get(opening);
    if (opening !== undefined) list(opening);
    if (page?.perEntry) {
      const expected = [...categories(page)].map(([category, items]) => ({
        group: category,
        pages: items.map(item => `${page.route}/${item.heading}`),
      }));
      const listedCategories =
        group.root === undefined ? group.pages.slice(1) : group.pages;
      if (JSON.stringify(listedCategories) !== JSON.stringify(expected)) {
        throw new Error(
          `docs.json: the group opened by ${page.route} must list its entries by category:\n${JSON.stringify(expected, null, 2)}`,
        );
      }
      for (const route of expected.flatMap(category => category.pages)) {
        list(route);
      }
      return;
    }
    for (const item of group.pages) {
      if (typeof item !== 'string') {
        walk(item);
        continue;
      }
      list(item);
      if (generated.get(item)?.perEntry) {
        throw new Error(
          `docs.json: ${item} must open its group, as its root or a section's first page`,
        );
      }
      if (
        !generated.has(item) &&
        !articles.some(article => article.route === item) &&
        !existsSync(path.join(root, 'docs', `${item}.md`))
      ) {
        throw new Error(`docs.json lists missing page ${item}`);
      }
    }
  };
  for (const group of await referenceTab(root)) walk(group);
  const unlisted = [
    ...pages.map(page => page.route),
    ...articles.map(article => article.route),
  ].filter(route => !listed.has(route));
  if (unlisted.length > 0) {
    throw new Error(
      `docs.json does not list generated pages: ${unlisted.join(', ')}`,
    );
  }
}

// ---- in-app manual ----------------------------------------------------------

// The CLI and the JavaScript API stay on the site; the A–Z index repeats the
// manual's search.
const OUTSIDE_MANUAL = {
  groups: ['Tools', 'JavaScript API'],
  routes: ['reference/a-z'],
};

/**
 * The script-facing Reference as data for `tea/reference`: every top-level
 * group of docs.json's Reference tab but Tools and JavaScript API, in order.
 * A per-entry page is one manual page whose entries are each followed by
 * their methods; generated and hand-written prose pages are articles. Links
 * stay inside the manual or keep only their text (see {@link manualLinks}).
 */
async function manual(
  root: string,
  pages: readonly Page[],
  articles: readonly Article[],
  index: SymbolIndex,
): Promise<ReferenceManual> {
  const generated = new Map(pages.map(page => [page.route, page]));
  const groups: {title: string; routes: string[]}[] = [];
  const collect = (node: string | NavigationGroup, routes: string[]) => {
    const opening =
      typeof node === 'string' ? undefined : openingPage(node, generated);
    if (typeof node === 'string') {
      if (!OUTSIDE_MANUAL.routes.includes(node)) routes.push(node);
    } else if (opening !== undefined) {
      routes.push(opening);
    } else {
      for (const child of node.pages) collect(child, routes);
    }
  };
  for (const group of await referenceTab(root)) {
    if (OUTSIDE_MANUAL.groups.includes(group.group)) continue;
    const routes: string[] = [];
    collect(group, routes);
    if (routes.length > 0) groups.push({title: group.group, routes});
  }
  const routes = new Set(groups.flatMap(group => group.routes));
  // A link may name any symbol of an entry, such as `color.red` of `color.*`,
  // or an entry's own page, and leads to the entry.
  const entryOf = new Map<string, string>();
  const entryAt = new Map<string, string>();
  for (const route of routes) {
    for (const item of generated.get(route)?.entries ?? []) {
      for (const owned of [item, ...item.members]) {
        for (const symbol of owned.symbols) {
          entryOf.set(symbol, owned.name);
          const target = index.get(symbol);
          if (target !== undefined) entryAt.set(href(target), owned.name);
        }
      }
    }
  }
  const text = (markdown: string, from: string) =>
    manualLinks(markdown, from, routes, entryOf, entryAt);
  const article = async (route: string): Promise<ReferencePage> => {
    const made = articles.find(candidate => candidate.route === route);
    const source =
      made === undefined
        ? await readFile(path.join(root, 'docs', `${route}.md`), 'utf8')
        : undefined;
    return {
      kind: 'article',
      id: route,
      title:
        made?.title ??
        (frontMatterValue(source!, 'sidebarTitle') ||
          frontMatterValue(source!, 'title')),
      description:
        made?.description ?? frontMatterValue(source!, 'description'),
      markdown: text(
        made?.markdown ?? source!.replace(/^---\n[\s\S]*?\n---\n/, '').trim(),
        route,
      ),
    };
  };
  const entries = (page: Page): ReferencePage => {
    const parameter = (param: ParamRow): ReferenceParameter => ({
      ...param,
      description: text(param.description, page.route),
    });
    const referenceEntry = (item: Entry): ReferenceEntry => {
      if (item.kind === 'class' || item.kind === 'command') {
        throw new Error(`${page.route}: ${item.name} cannot be in the manual`);
      }
      return {
        id: item.name,
        symbols: item.symbols,
        kind: item.kind,
        category: item.category,
        summary: text(item.summary, page.route),
        signatures: item.signatures.map(signature => wrapSignature(signature)),
        parameters: item.params.map(parameter),
        returns: item.returns === null ? null : text(item.returns, page.route),
        members:
          item.table === null
            ? null
            : {
                columns: item.table.columns,
                rows: item.table.rows.map(row =>
                  row.map(value => text(value, page.route)),
                ),
              },
        body: text(item.body, page.route),
      };
    };
    return {
      kind: 'entries',
      id: page.route,
      title: page.title,
      description: text(page.description, page.route),
      intro: text(page.intro, page.route),
      commonParameters: page.shared.map(parameter),
      entries: page.entries.flatMap(item => [
        referenceEntry(item),
        ...item.members.map(referenceEntry),
      ]),
    };
  };
  return {
    groups: await Promise.all(
      groups.map(async group => ({
        title: group.title,
        pages: await Promise.all(
          group.routes.map(route => {
            const page = generated.get(route);
            return page === undefined ? article(route) : entries(page);
          }),
        ),
      })),
    ),
  };
}

/**
 * Links for the in-app manual: `{@link ta.sma}`, a link to an entry's page
 * and a link to a manual page become `#ta.sma` and `#reference/builtins/ta`,
 * which the host resolves inside the manual. A link to a page outside the
 * manual, such as a guide, or to a heading on the same page keeps only its
 * text; a link with a scheme stays.
 */
function manualLinks(
  markdown: string,
  from: string,
  routes: ReadonlySet<string>,
  entryOf: ReadonlyMap<string, string>,
  entryAt: ReadonlyMap<string, string>,
): string {
  return markdown
    .replace(LINK, (_, target: string, label: string | undefined) => {
      const id = entryOf.get(target);
      return id === undefined
        ? code(label ?? target)
        : `[${code(label ?? target)}](#${id})`;
    })
    .replace(
      /\[([^\]]+)\]\(([^)\s]+)\)/g,
      (whole, label: string, link: string) => {
        if (/^[a-z][a-z0-9+.-]*:/i.test(link)) return whole;
        // An entry link from above stays; an anchor to a heading on the same
        // page has nothing to point at in the manual.
        if (link.startsWith('#')) {
          return [...entryOf.values()].includes(link.slice(1)) ? whole : label;
        }
        const [target = '', anchor] = link.split('#');
        const route = target.startsWith('/')
          ? target.slice(1).replace(/\/$/, '')
          : path.posix
              .normalize(path.posix.join(path.posix.dirname(from), target))
              .replace(/\.md$/, '');
        const entry =
          entryAt.get(
            anchor === undefined ? `/${route}` : `/${route}#${anchor}`,
          ) ?? entryAt.get(`/${route}`);
        if (entry !== undefined) return `[${label}](#${entry})`;
        return routes.has(route) ? `[${label}](#${route})` : label;
      },
    );
}

// ---- outputs ----------------------------------------------------------------

function symbolIndex(
  pages: readonly Page[],
  scope: Page['scope'],
): Map<string, Target> {
  const index = new Map<string, Target>();
  for (const page of pages.filter(candidate => candidate.scope === scope)) {
    for (const [symbol, target] of targets(page)) {
      if (index.has(symbol)) {
        // One JavaScript declaration can be exported by several entry points;
        // links go to the first in package.json order.
        if (scope === 'javascript') continue;
        throw new Error(
          `${symbol} is documented on both ${index.get(symbol)!.route} and ${page.route}`,
        );
      }
      index.set(symbol, target);
    }
  }
  return index;
}

/**
 * Every example the Tea reference shows, with the entry it documents: the
 * natives' and every shipped library's, members included.
 */
function referenceExamples(
  libraries: readonly TeaLibrary[],
): [string, DocExample][] {
  const docs: [string, DocComment | null][] = [
    ...Object.keys(NATIVE_FUNCTION_DOCS).map(
      name => [name, nativeFunctionDocs(name)] as [string, DocComment | null],
    ),
    ...Object.keys(NATIVE_VALUE_DOCS).map(
      name => [name, nativeValueDocs(name)] as [string, DocComment | null],
    ),
    ...libraries.flatMap(library => [
      [`library ${library.name}`, library.doc] as [string, DocComment | null],
      ...library.exports.flatMap(item => [
        [qualifiedName(library, item.name), item.doc] as [
          string,
          DocComment | null,
        ],
        ...item.members.map(
          member =>
            [
              `${qualifiedName(library, item.name)}.${member.name}`,
              member.doc,
            ] as [string, DocComment | null],
        ),
      ]),
    ]),
  ];
  return docs.flatMap(([where, doc]) =>
    (doc?.examples ?? []).map(
      (example, index) =>
        [`${where} example ${index + 1}`, example] as [string, DocExample],
    ),
  );
}

/** Every generated reference file, keyed by its path. */
export async function referenceOutputs(
  root = ROOT,
): Promise<ReadonlyMap<string, string>> {
  const libraries = teaLibraries();
  const written = await runExamples(referenceExamples(libraries));
  const outputs: Outputs = doc =>
    doc.examples.map(example => written.get(exampleKey(example))!);
  const pages = [
    ...builtinPages(libraries, outputs),
    ...libraryPages(libraries, outputs),
    cliPage(),
    ...javascriptPages(),
  ];
  const indexes = {
    tea: symbolIndex(pages, 'tea'),
    javascript: symbolIndex(pages, 'javascript'),
  };
  const articles = [
    overviewArticle(libraries),
    await indexArticle(root, pages, indexes.tea),
    pineArticle(libraries, pages, indexes.tea),
  ];
  await checkNavigation(root, pages, articles);
  const file = (route: string) => path.join(root, 'docs', `${route}.md`);
  return new Map([
    [
      path.join(root, 'docs/assets/tea.tmLanguage.json'),
      JSON.stringify({...generateGrammar(), name: 'tea', displayName: 'Tea'}),
    ],
    [
      path.join(root, 'src/reference/manual.json'),
      JSON.stringify(await manual(root, pages, articles, indexes.tea)),
    ],
    ...articles.map(
      article =>
        [file(article.route), articleFile(article, indexes.tea)] as const,
    ),
    ...pages.flatMap(page =>
      pageFiles(page, indexes[page.scope]).map(
        ([route, markdown]) => [file(route), markdown] as const,
      ),
    ),
  ]);
}

/**
 * Turn site routes (`/requests`, `/reference/builtins/ta#tasma`) into links to
 * real sibling files, so the Markdown reads the same on the web and inside an
 * extracted package. A route without a page is an error.
 */
function portableLinks(content: string, file: string, root: string): string {
  return content.replace(
    /\]\(\/([^)#\s]*)(#[^)\s]*)?\)/g,
    (_, route: string, anchor = '') => {
      const target = path.join(root, 'docs', `${route.replace(/\/$/, '')}.md`);
      if (!existsSync(target) && !route.startsWith('reference/')) {
        throw new Error(
          `${path.relative(root, file)} links to missing page /${route}`,
        );
      }
      const relative = path
        .relative(path.dirname(file), target)
        .split(path.sep)
        .join('/');
      return `](${relative.startsWith('.') ? relative : `./${relative}`}${anchor})`;
    },
  );
}

async function generatedFiles(directory: string): Promise<string[]> {
  const found: string[] = [];
  for (const item of await readdir(directory, {withFileTypes: true})) {
    const file = path.join(directory, item.name);
    if (item.isDirectory()) found.push(...(await generatedFiles(file)));
    else if (
      item.name.endsWith('.md') &&
      (await readFile(file, 'utf8')).includes(GENERATED)
    ) {
      found.push(file);
    }
  }
  return found;
}

interface GenerateOptions {
  readonly root?: string;
  readonly check?: boolean;
  readonly report?: (message: string) => void;
}

/** Write the reference, or with `check` report every file that would change. */
export async function generateReference(
  options: GenerateOptions = {},
): Promise<boolean> {
  const root = options.root ?? ROOT;
  const check = options.check ?? false;
  const report = options.report ?? (message => console.error(message));
  let stale = false;
  const outputs = await referenceOutputs(root);
  for (const [file, content] of outputs) {
    const formatted = await format(
      path.extname(file) === '.json'
        ? content
        : portableLinks(content, file, root),
      {parser: path.extname(file) === '.json' ? 'json' : 'mdx'},
    );
    const current = existsSync(file) ? await readFile(file, 'utf8') : undefined;
    if (current === formatted) continue;
    if (check) {
      stale = true;
      report(`Generated reference is stale: ${path.relative(root, file)}`);
      continue;
    }
    await mkdir(path.dirname(file), {recursive: true});
    await writeFile(file, formatted, 'utf8');
  }
  for (const file of await generatedFiles(path.join(root, 'docs/reference'))) {
    if (outputs.has(file)) continue;
    if (check) {
      stale = true;
      report(
        `Generated reference page has no source: ${path.relative(root, file)}`,
      );
      continue;
    }
    await rm(file);
    // Drop directories the removed page leaves empty, up to docs/reference.
    for (
      let directory = path.dirname(file);
      directory !== path.join(root, 'docs/reference') &&
      (await readdir(directory)).length === 0;
      directory = path.dirname(directory)
    ) {
      await rm(directory, {recursive: true});
    }
  }
  if (!stale && check) console.log('Generated Tea reference is current.');
  return !stale;
}

if (
  process.argv[1] !== undefined &&
  path.resolve(process.argv[1]) === SCRIPT_FILE
) {
  const current = await generateReference({
    check: process.argv.includes('--check'),
  });
  if (!current) process.exitCode = 1;
}
