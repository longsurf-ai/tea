// ---- page model -------------------------------------------------------------

interface ParamRow {
  readonly name: string;
  readonly type: string | null;
  readonly defaultValue: string | null;
  readonly description: string;
}

/** What an entry documents, for readers that label or format it by kind. */
type EntryKind =
  | 'function'
  | 'variable'
  | 'constant'
  | 'type'
  | 'enum'
  | 'interface'
  | 'class'
  | 'command';

interface Entry {
  /** As code writes it: `ta.sma`, `trade.NextOpenTrade`, `tea run`. */
  readonly name: string;
  readonly kind: EntryKind;
  /**
   * The page heading. Mintlify and Docusaurus slug punctuation differently
   * (`ta.sma` becomes `ta-sma` in one and `tasma` in the other) and neither
   * reads explicit ids from both, so headings hold only letters, digits, `_`
   * and spaces: the name within its page's namespace, `sma` on the `ta` page.
   * Empty for a table that sits directly under its category heading.
   */
  readonly heading: string;
  /** Names a `{@link …}` resolves to this entry. */
  readonly symbols: readonly string[];
  readonly summary: string;
  /** One per overload; a long one may span lines. */
  readonly signatures: readonly string[];
  readonly params: readonly ParamRow[];
  readonly returns: string | null;
  /** One table row per member: its declaration, value or name, then notes. */
  readonly table: {
    readonly columns: readonly string[];
    readonly rows: readonly (readonly string[])[];
  } | null;
  readonly body: string;
  /** Methods, each with its own heading under its owner. */
  readonly members: readonly Entry[];
  /** A difference from Pine Script v6, listed on the compatibility page. */
  readonly pine: string | null;
  readonly category: string;
}

interface Page {
  readonly route: string;
  readonly title: string;
  readonly description: string;
  readonly intro: string;
  readonly language: 'tea' | 'ts' | 'bash';
  readonly scope: 'tea' | 'javascript';
  /** What the parameter table calls its rows: `Parameter` or `Argument`. */
  readonly paramLabel: string;
  readonly entries: readonly Entry[];
  /** Parameters documented once for the page instead of on every entry. */
  readonly shared: readonly ParamRow[];
  /**
   * Each entry has its own page at `<route>/<heading>`, and this page lists
   * them by category.
   */
  readonly perEntry: boolean;
}

function entry(
  fields: Partial<Entry> &
    Pick<Entry, 'name' | 'kind' | 'summary' | 'category'>,
): Entry {
  return {
    heading: fields.name.slice(fields.name.lastIndexOf('.') + 1),
    symbols: [fields.name],
    signatures: [],
    params: [],
    returns: null,
    table: null,
    body: '',
    members: [],
    pine: null,
    ...fields,
  };
}

